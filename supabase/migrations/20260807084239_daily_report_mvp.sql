GRANT SELECT, INSERT, UPDATE, DELETE ON public.daily_report_items TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.news_sources TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.report_item_sources TO service_role;
